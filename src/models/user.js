const mongoose=require("mongoose");
const userSchema= new mongoose.Schema({
        fristName:{
            type:String,
            required:true,
            minLength:4,
            maxLength:50,
        },
        lastName:{
            type:String,
        },
        emailId:{
            type:String,
            lowercase:true,
            required:true,
            unique:true,
            trim:true,
        },
        password:{
            type:String,
            required:true
        },
        age:{
            type:Number,
            min:4,
        },
        gender:{
            type:String,
            validate(value){
                if(!["Male","Female","other"].includes(value)){
                    throw new Error("Gender data is not valid")
                }
            },
        },
        photoUrl:{
            type:String
        },
        about:
        {
            type:String,
            default:"This is the default value of user",
        },
        skill:{
            type:[String],
        },
    },
    {
        timestamps:true
    },
);
module.exports=mongoose.model("user",userSchema)